/* 年代 / 生卒 / 尺寸里的中文限定词 → 英文（目录里这几个字段是纯字符串） */
const ORD = (n) => { const a = ['th','st','nd','rd'], v = n % 100; return n + (a[(v - 20) % 10] || a[v] || a[0]); };
export function enDate(v) {
  let s = String(v ?? '');
  if (!/[\u4e00-\u9fff\uff08\uff09]/.test(s)) return s;
  const after = /之后/.test(s);
  s = s.replace(/\s*之后/g, '')
       .replace(/完成于\s*/g, 'completed ')
       .replace(/全卷\s*/g, 'full scroll ')
       .replace(/（\s*宋摹本\s*）/g, ' (Song copy)')
       .replace(/（\s*开启\s*）/g, ' (open)')
       .replace(/(\d+)\s*世纪初/g, (m, n) => 'early ' + ORD(+n) + ' century')
       .replace(/(\d+)\s*世纪末/g, (m, n) => 'late ' + ORD(+n) + ' century')
       .replace(/(\d+)\s*世纪/g, (m, n) => ORD(+n) + ' century')
       .replace(/约\s*/g, 'c. ')
       .replace(/（/g, ' (').replace(/）/g, ')')
       .replace(/\s+/g, ' ').trim().replace(/^c\. (early|late) /, '$1 ');
  return after ? 'after ' + s : s;
}

